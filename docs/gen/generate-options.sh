#!/usr/bin/env bash
set -euo pipefail

repo_root="$(git rev-parse --show-toplevel)"
output_file="$repo_root/docs/reference/options.md"

mkdir -p "$(dirname "$output_file")"

options="$(bash "$repo_root/docs/gen/devenv-build.sh" outputs.docs-options)"

{
  printf '%s\n' '[comment]: # (DO NOT MODIFY. This file was generated by generate-docs.)'
  printf '\n# Options\n\n'
  sed 's/\\\././g' "$options"
} >"$output_file"
